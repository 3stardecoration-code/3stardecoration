"use client";

import Link from "next/link";
import { usePathname } from "next/navigation";
import { useEffect } from "react";
import { useAdminNav } from "./AdminNavContext";

const NAV_ITEMS = [
  { label: "Dashboard", href: "/admin", icon: HomeIcon },
  { label: "Homepage", href: "/admin/homepage", icon: LayoutIcon },
  { label: "About Page", href: "/admin/about", icon: InfoIcon },
  { label: "Enquiries", href: "/admin/enquiries", icon: InboxIcon },
  { label: "Portfolio", href: "/admin/portfolio", icon: BriefcaseIcon },
  { label: "Services", href: "/admin/services", icon: LayersIcon },
  { label: "Testimonials", href: "/admin/testimonials", icon: QuoteIcon },
  { label: "Media Library", href: "/admin/media", icon: ImageIcon },
  { label: "Settings", href: "/admin/settings", icon: SettingsIcon },
];

export function AdminSidebar() {
  const pathname = usePathname();
  const { open, setOpen } = useAdminNav();

  // Close the mobile drawer automatically whenever the route changes.
  useEffect(() => {
    setOpen(false);
  }, [pathname, setOpen]);

  return (
    <>
      {/* Backdrop — mobile only, shown while the drawer is open */}
      {open && (
        <div
          aria-hidden
          onClick={() => setOpen(false)}
          className="fixed inset-0 z-30 bg-black/40 lg:hidden"
        />
      )}

      <aside
        className={`fixed inset-y-0 left-0 z-40 flex w-72 flex-col border-r border-gray-200 bg-white transition-transform duration-300 lg:w-64 lg:translate-x-0 ${
          open ? "translate-x-0" : "-translate-x-full"
        }`}
      >
        {/* Logo Area */}
        <div className="flex h-16 shrink-0 items-center justify-between border-b border-gray-100 px-6">
          <span className="font-[family-name:var(--font-display)] text-lg font-medium text-gray-900">
            <span className="text-[#a48252] mr-1.5" aria-hidden>✦</span>
            3 Star CMS
          </span>
          <button
            type="button"
            onClick={() => setOpen(false)}
            aria-label="Close menu"
            className="text-gray-400 hover:text-gray-600 lg:hidden"
          >
            ✕
          </button>
        </div>

      {/* Navigation */}
      <nav className="flex-1 overflow-y-auto px-4 py-6">
        <ul className="flex flex-col gap-1.5">
          {NAV_ITEMS.map((item) => {
            const isActive =
              item.href === "/admin"
                ? pathname === "/admin"
                : pathname.startsWith(item.href);

            return (
              <li key={item.href}>
                <Link
                  href={item.href}
                  className={`flex items-center gap-3 rounded-lg px-3 py-2.5 text-sm font-medium transition-colors ${
                    isActive
                      ? "bg-gray-100 text-gray-900"
                      : "text-gray-600 hover:bg-gray-50 hover:text-gray-900"
                  }`}
                >
                  <item.icon className={`h-5 w-5 ${isActive ? "text-gray-900" : "text-gray-400"}`} />
                  {item.label}
                </Link>
              </li>
            );
          })}
        </ul>
      </nav>

      {/* Bottom Area (e.g. Back to site) */}
      <div className="border-t border-gray-100 p-4">
        <Link
          href="/"
          target="_blank"
          className="flex items-center gap-3 rounded-lg px-3 py-2 text-sm font-medium text-gray-500 transition-colors hover:bg-gray-50 hover:text-gray-900"
        >
          <ExternalLinkIcon className="h-5 w-5 text-gray-400" />
          View Live Site
        </Link>
      </div>
      </aside>
    </>
  );
}

